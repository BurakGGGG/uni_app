/// ÖSYM "YKS Yerleştirme Puanlarının Yığınsal Dağılımı" tabloları.
///
/// Kaynak: ÖSYM sayısal bilgiler PDF'leri (sayfa 13, yerleştirme puanları) —
/// dokuman.osym.gov.tr/pdfdokuman/{yıl}/YKS/sayisalbilgiler*.pdf
/// (2025: 21.07.2025, 2024: 16.07.2024, 2023: 20.07.2023, 2022: 18.07.2022).
///
/// Her satır: (yerleştirme puanı eşiği, o puan ve üstü aday sayısı) — yani
/// eşikteki resmî başarı sırası. Sıra tahmini bu çapalar arasında log-uzayda
/// doğrusal enterpolasyonla yapılır; taban puanlardan türetilen eğriye göre
/// çok daha isabetlidir çünkü tüm aday kitlesini kapsar.
class OsymScoreDistribution {
  const OsymScoreDistribution._();

  /// Verilen yerleştirme puanının resmî dağılıma göre tahmini başarı sırası.
  ///
  /// İstenen yılın tablosu yoksa en yakın küçük yıla düşer (2026 → 2025);
  /// dönen `year` istenen yıldan farklıysa UI "X verisine göre" etiketi basar.
  static ({int rank, int year})? estimateRank(
      double score, String scoreType, int year) {
    if (score <= 0) return null;
    final resolved = _resolveYear(scoreType, year);
    if (resolved == null) return null;
    final anchors = _tables[resolved]![scoreType.toUpperCase()]!;
    return (rank: _interpolate(anchors, score), year: resolved);
  }

  /// [estimateRank]'in tersi: verilen başarı sırasına karşılık gelen
  /// yerleştirme puanı. Kullanıcı netleri yerine sırasını girdiğinde puanı
  /// buradan türetilir.
  ///
  /// `clamped` true ise sıra tablonun dışında kalmıştır ve dönen puan uç
  /// çapadır (en üstte 550, en altta 115) — UI "550+" gibi bir dil kullanmalı,
  /// çünkü o aralıkta tek bir puan söylenemez.
  static ({double score, int year, bool clamped})? estimateScore(
      int rank, String scoreType, int year) {
    if (rank <= 0) return null;
    final resolved = _resolveYear(scoreType, year);
    if (resolved == null) return null;
    final anchors = _tables[resolved]![scoreType.toUpperCase()]!;
    final (score, clamped) = _interpolateScore(anchors, rank);
    return (score: score, year: resolved, clamped: clamped);
  }

  /// Bu tür için puanı hesaplanan toplam aday sayısı (yüzdelik dilim paydası).
  static ({int count, int year})? totalCandidates(String scoreType, int year) {
    final resolved = _resolveYear(scoreType, year);
    if (resolved == null) return null;
    final anchors = _tables[resolved]![scoreType.toUpperCase()]!;
    return (count: anchors.last.$2, year: resolved);
  }

  static int? _resolveYear(String scoreType, int year) {
    final type = scoreType.toUpperCase();
    int? below;
    int? above;
    for (final y in _tables.keys) {
      if (!_tables[y]!.containsKey(type)) continue;
      if (y == year) return y;
      if (y < year && (below == null || y > below)) below = y;
      if (y > year && (above == null || y < above)) above = y;
    }
    return below ?? above;
  }

  /// Çapalar puana göre azalan sıralı. Uçların dışı uca kelepçelenir;
  /// aradaki puanlar için aday sayısı log-uzayda enterpole edilir.
  static int _interpolate(List<(double, int)> anchors, double score) {
    if (score >= anchors.first.$1) return math.max(1, anchors.first.$2);
    if (score <= anchors.last.$1) return anchors.last.$2;
    for (var i = 0; i < anchors.length - 1; i++) {
      final (hiScore, hiCount) = anchors[i];
      final (loScore, loCount) = anchors[i + 1];
      if (score >= loScore) {
        final t = (hiScore - score) / (hiScore - loScore);
        final ln = math.log(hiCount) +
            (math.log(loCount) - math.log(hiCount)) * t;
        return math.exp(ln).round();
      }
    }
    return anchors.last.$2;
  }

  /// [_interpolate]'in cebirsel tersi. Aday sayıları puan azaldıkça arttığı
  /// için çapalar sıraya göre ARTAN okunur; kiriş içinde ln(aday) doğrusal
  /// varsayıldığından puan da doğrusal olarak geri çözülür.
  static (double, bool) _interpolateScore(
      List<(double, int)> anchors, int rank) {
    if (rank <= anchors.first.$2) return (anchors.first.$1, true);
    if (rank >= anchors.last.$2) return (anchors.last.$1, true);
    for (var i = 0; i < anchors.length - 1; i++) {
      final (hiScore, hiCount) = anchors[i];
      final (loScore, loCount) = anchors[i + 1];
      if (rank <= loCount) {
        // Kuyruktaki düz plato (loCount == hiCount): sıra bu kirişte tek bir
        // puana çözülemez, üst eşiği veririz.
        if (loCount == hiCount) return (hiScore, true);
        final t = (math.log(rank) - math.log(hiCount)) /
            (math.log(loCount) - math.log(hiCount));
        return (hiScore - t * (hiScore - loScore), false);
      }
    }
    return (anchors.last.$1, true);
  }

